function addTitleSlide(pptx, title, subtitle) {
  const slide = pptx.addSlide();
  slide.addText(title, { x: 0.5, y: 1.0, w: 9, h: 1.0, fontFace: 'Tahoma', fontSize: 36, bold: true, color: '363636' });
  if (subtitle) {
    slide.addText(subtitle, { x: 0.5, y: 2.0, w: 9, h: 1.0, fontFace: 'Tahoma', fontSize: 18, color: '666666' });
  }
}

function addBulletsSlide(pptx, title, bullets) {
  const slide = pptx.addSlide();
  slide.addText(title, { x: 0.5, y: 0.6, w: 9, h: 0.6, fontFace: 'Tahoma', fontSize: 28, bold: true, color: '363636' });
  const text = bullets.map(b => ({ text: b, options: { bullet: true, fontFace: 'Tahoma', fontSize: 18, color: '333333', breakLine: true } }));
  slide.addText(text, { x: 0.8, y: 1.4, w: 8.4, h: 4.5 });
}

